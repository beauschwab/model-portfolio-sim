"""Generate a bounded JSON HTTP client surface from FastAPI OpenAPI, or check drift.

No lifespan is entered, database opened, or calculation executed. Arrow/Parquet
result endpoints deliberately remain in the handwritten transport client.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def render(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1].replace('-', '_')
    if 'enum' in schema:
        return ' | '.join(json.dumps(x) for x in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    for key in ('anyOf', 'oneOf', 'allOf'):
        if key in schema:
            return '(' + (' & ' if key == 'allOf' else ' | ').join(render(x) for x in schema[key]) + ')'
    kind = schema.get('type')
    if isinstance(kind, list):
        return '(' + ' | '.join(render(dict(schema, type=k)) for k in kind) + ')'
    if kind in ('integer', 'number'): return 'number'
    if kind in ('string', 'boolean', 'null'): return kind
    if kind == 'array': return f'Array<{render(schema["items"])}>'
    if kind == 'object' or 'properties' in schema:
        fields = [f'{json.dumps(k)}'+('' if k in schema.get('required', []) else '?')+f': {render(v)};'
                  for k,v in schema.get('properties', {}).items()]
        extra = schema.get('additionalProperties')
        if isinstance(extra, dict): fields.append(f'[key: string]: {render(extra)};')
        elif extra is True: fields.append('[key: string]: unknown;')
        return '{ ' + ' '.join(fields) + ' }'
    if not schema or set(schema) <= {'title', 'description', 'default'}: return 'unknown'
    raise ValueError(f'Unsupported JSON schema: {schema}')


def artifacts():
    sys.path.insert(0, str(ROOT/'apps/api'))
    from app.main import app
    document = app.openapi()
    schemas = document['components']['schemas']
    aliases = {}
    for name, path in [('HttpSettings','/settings'), ('HttpMarket','/market'),
                       ('HttpState','/state'), ('HttpJob','/jobs/{jid}'),
                       ('HttpStressCapabilities','/balance-stress/capabilities')]:
        aliases[name] = document['paths'][path]['get']['responses']['200']['content']['application/json']['schema']
        if '$ref' not in aliases[name]: raise ValueError(f'{path} must declare a response model')
    selected = ['ForecastRequest', 'MarketScenario', 'RunRequest', 'Allocation', 'DatedBalanceStressRequest', 'CreditBalanceStressRequest', 'CreditPathBalanceStressRequest','ModeledBalanceStressRequest', 'ModelRunRequest', 'PublishedHoldingRequest', 'MortgageClosingRequest', 'ModeledProductFTPRequest', 'ModeledFTPSourceMetadata', 'SavedDerivativeMixedRequest', 'SavedDerivativeDepositPortfolioRequest']
    pending = list(aliases.values()) + [{'$ref': '#/components/schemas/'+name} for name in selected]
    used = {}
    while pending:
        value = pending.pop()
        if isinstance(value, list): pending.extend(value)
        elif isinstance(value, dict):
            if '$ref' in value:
                name = value['$ref'].rsplit('/',1)[-1]
                if name not in used:
                    used[name] = schemas[name]; pending.append(schemas[name])
            pending.extend(v for k,v in value.items() if k != '$ref')
    contract = {'openapi':document['openapi'], 'schemas':used, 'responses':aliases}
    text = '// Generated by scripts/generate_http_contracts.py. Do not edit.\n'
    text += '// JSON routes only; Arrow tables and partition descriptors are handwritten.\n\n'
    text += '\n'.join(f'export type {name.replace("-","_")} = {render(value)};'
                      for name,value in sorted(used.items())) + '\n\n'
    text += '\n'.join(f'export type {name} = {render(value)};' for name,value in sorted(aliases.items()))+'\n'
    return {ROOT/'apps/web/src/lib/http.generated.ts':text,
            ROOT/'docs/contracts/http-openapi.json':json.dumps(contract,indent=2,sort_keys=True)+'\n'}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    bad=[]
    for path,text in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text: bad.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8')
    if bad: raise SystemExit('HTTP contract drift: '+', '.join(map(str,bad))+'; run scripts/generate_http_contracts.py')
    print('HTTP contracts '+('verified' if args.check else 'generated'))


if __name__ == '__main__': main()
